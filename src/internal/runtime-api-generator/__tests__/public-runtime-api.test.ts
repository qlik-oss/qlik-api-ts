import { afterEach, beforeEach, describe, expect, it, vi, type MockInstance } from "vitest";
import { clearCsrfToken } from "#internal/http/http-functions";
import { clearPlatform } from "#internal/platform/platform-functions";
import type { ApiCallOptions, InvokeFetchProperties, InvokeFetchResponse } from "#public/invoke-fetch";
import * as invokFetchMethods from "#public/invoke-fetch";
import { apiKeys, apps, reloadTasks, spaces } from "../../../index";
import type { UrlSegmentNode } from "../runtime-api-generator-common";
import { apiDefToApiPublic } from "../runtime-api-generator-public";

type RuntimeApi = {
  clearCache: () => void;
};

describe("public-runtime-api tests", () => {
  beforeEach(() => {
    clearCsrfToken();
    clearPlatform();
    fetchMock.resetMocks();
  });

  describe("Runtime API modules", () => {
    let invokeFetchSpy: MockInstance<
      (this: Promise<InvokeFetchResponse>, api: string, props: InvokeFetchProperties) => Promise<InvokeFetchResponse>
    >;

    beforeEach(() => {
      invokeFetchSpy = vi.spyOn(invokFetchMethods, "invokeFetch");
    });
    afterEach(() => {
      vi.clearAllMocks();
    });
    it("should be importable", async () => {
      expect(apiKeys).toBeTruthy();
      expect(apps).toBeTruthy();
      expect(reloadTasks).toBeTruthy();
      expect(spaces).toBeTruthy();
    });
    it("should have clearCache", async () => {
      expect(apiKeys).toHaveProperty("clearCache");
    });
    it("should call correct urls", async () => {
      fetchMock.mockResponse((req) => {
        if (req.url.includes("/resources/autogenerated/product-info.json")) {
          return Promise.resolve("{}");
        }
        if (req.url.includes("/api/v1/api-keys/123") || req.url.includes("/api/v1/reload-tasks/123")) {
          return Promise.resolve(JSON.stringify({ id: "123" }));
        }
        if (req.url.includes("/api/v1/api-keys")) {
          return Promise.resolve(
            JSON.stringify({
              data: [{ id: "123" }],
            }),
          );
        }
        if (req.url.includes("/api/v1/spaces?name=gustaf")) {
          return Promise.resolve(
            JSON.stringify({
              data: [{ name: "gustaf" }],
            }),
          );
        }
        if (req.url.includes("/api/v1/spaces/123/assignments/456")) {
          return Promise.resolve(JSON.stringify({ id: "456" }));
        }
        // Default case for any other URL
        return Promise.resolve("");
      });

      // @ts-expect-error ts(2554)
      const res1 = await apiKeys.getApiKeys();
      expect(invokeFetchSpy).toHaveBeenNthCalledWith(
        1,
        "api-keys",
        {
          body: undefined,
          method: "GET",
          options: undefined,
          pathTemplate: "/api/v1/api-keys",
          pathVariables: {},
          query: undefined,
        },
        [],
      );
      expect(res1.status).toBe(200);
      expect(res1.data?.data?.[0]?.id).toBe("123");
      const res2 = await apiKeys.getApiKey("123");
      expect(res2.status).toBe(200);
      expect(res2.data?.id).toBe("123");
      const res3 = await reloadTasks.getReloadTask("123");
      expect(res3.status).toBe(200);
      expect(res3.data?.id).toBe("123");
      const res4 = await spaces.getSpaces({ name: "gustaf" });
      expect(res4.status).toBe(200);
      expect(res4.data?.data?.[0]?.name).toBe("gustaf");
      const res5 = await spaces.getSpaceAssignment("123", "456");
      expect(res5.status).toBe(200);
      expect(res5.data?.id).toBe("456");
    });
    it("should handle query, body and options", async () => {
      fetchMock.mockResponse((req) => {
        if (req.url.includes("/resources/autogenerated/product-info.json")) {
          return Promise.resolve("{}");
        }
        if (req.url.includes("/api/v1/api-keys?name=gustaf")) {
          return Promise.resolve(
            JSON.stringify({
              data: [{ name: "gustaf" }],
            }),
          );
        }
        if (req.url.includes("/api/v1/apps/import?name=Banana")) {
          return Promise.resolve(
            JSON.stringify({
              attributes: { name: "Banana" },
            }),
          );
        }
        return Promise.resolve("");
      });
      const body = "0xbinarybitsandbytesnothingtosee";
      await apps.importApp({ name: "Banana" }, body);
      expect(fetch).toHaveBeenNthCalledWith(
        3,
        "/api/v1/apps/import?name=Banana",
        expect.objectContaining({
          body,
          headers: expect.objectContaining({ "Content-Type": "application/octet-stream" }),
        }),
      );
    });
  });

  describe("Runtime API generator", () => {
    it("should generate correct, callable API from definition", async () => {
      type Item = { name?: string; title?: string; id: string };
      type Response = { status: number };
      type ListResponse = {
        data: {
          data: Array<Item>;
        };
      } & Response;
      type SingleResponse = {
        data: {
          data: Item;
        };
      } & Response;
      type ComposersApi = RuntimeApi & {
        listComposers: (query: Record<string, unknown>) => Promise<ListResponse>;
        createComposer: (query: Record<string, string>, body: unknown, options?: ApiCallOptions) => Promise<unknown>;
        getComposer: (id: string, options?: ApiCallOptions) => Promise<SingleResponse>;
        listOpuses: (id: string, options?: ApiCallOptions) => Promise<ListResponse>;
        getOpus: (id: string, opusId: string, options?: ApiCallOptions) => Promise<SingleResponse>;
      };
      const definition: UrlSegmentNode = {
        composers: {
          "": ["listComposers:GQ:", "createComposer:PQB:"],
          "{id}": {
            "": ["getComposer:G:"],
            opuses: {
              "": ["listOpuses:G:"],
              "{opusId}": ["getOpus:G:"],
            },
          },
        },
      };
      // Using "newFormat" hence the true, just so we have some coverage.
      const api = apiDefToApiPublic<ComposersApi>("composers", definition)();
      for (const prop of ["listComposers", "createComposer", "getComposer", "listOpuses", "getOpus"]) {
        expect(api).toHaveProperty(prop);
      }
      fetchMock.mockResponse((req) => {
        if (req.url.includes("/resources/autogenerated/product-info.json")) {
          return Promise.resolve("{}");
        }
        if (req.url.includes("/composers?category=goat")) {
          return Promise.resolve(
            JSON.stringify({
              data: [{ name: "Darude", id: "1337" }],
            }),
          );
        }
        if (req.url.includes("/composers/1337/opuses/007")) {
          return Promise.resolve(
            JSON.stringify({
              data: { title: "Sandstorm", id: "007" },
            }),
          );
        }
        if (req.url.includes("/composers/1337/opuses")) {
          return Promise.resolve(
            JSON.stringify({
              data: [{ title: "Sandstorm", id: "007" }],
            }),
          );
        }
        if (req.url.includes("/api/v1/csrf-token")) {
          return Promise.resolve(JSON.stringify({ body: "ok", status: 200, headers: { "qlik-csrf-token": "abc123" } }));
        }
        // Default case for any other URL
        return Promise.resolve("");
      });

      const res1 = await api.listComposers({ category: "goat" });
      expect(res1?.status).toBe(200);
      expect(res1?.data?.data?.[0]?.name).toBe("Darude");
      const composerId = res1?.data?.data?.[0]?.id;
      const res2 = await api.listOpuses(composerId);
      expect(res2?.status).toBe(200);
      expect(res2?.data?.data?.[0]?.title).toBe("Sandstorm");
      const opusId = res2?.data?.data?.[0]?.id;
      const res3 = await api.getOpus(composerId, opusId);
      expect(res3?.status).toBe(200);
      expect(res3?.data?.data?.title).toBe("Sandstorm");

      await api.createComposer({ category: "goat" }, { name: "Boomfunk MC" }, { headers: { "x-coolness": "<9000" } });
      // one for product-info,
      // one for the composers,
      // one for the opuses,
      // one for the specific opus,
      // one for the csrf-token, (because of a post command)
      // one for the createComposer
      expect(fetch).toHaveBeenCalledTimes(6);
      expect(fetch).toHaveBeenNthCalledWith(
        6,
        "/composers?category=goat",
        expect.objectContaining({
          body: JSON.stringify({ name: "Boomfunk MC" }),
          headers: expect.objectContaining({ "x-coolness": "<9000" }),
        }),
      );
    });
  });
});
