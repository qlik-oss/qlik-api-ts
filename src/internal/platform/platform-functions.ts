/**
 * Clears the cached information for the supplied hostConfig. Mostly intended for test cases.
 * @private
 * @param hostConfig
 */
export function clearPlatform(hostConfig?: HostConfig) {
  const url = toValidLocationUrl(hostConfig);
  const completeUrl = templateUrl(url);
  delete productInfoPromises[completeUrl];
}

export const getPlatform = async (options: Options = {}): Promise<Platform> => {
  const hc = resolveHostConfig(options.hostConfig);
  if (hc.authType === "mock-backend-rest-recorder") {
    return hc.recordGetPlatform();
  }
  if (hc?.authType === "mock-backend") {
    return hc.mockGetPlatform();
  }
  if (hc?.authType === "noauth") {
    // when noauth module is configured platform is unknown
    return result({ isUnknown: true });
  }
  // Check if product info is available through QlikMain for the specified host.
  let productInfo: ProductInfo | undefined;
  if (isBrowser()) {
    try {
      const rootUrl = new URL(window.QlikMain?.getRootUrl() || "");
      const origin = hc.host ? new URL(hc.host)?.origin : window.location.origin;
      if (rootUrl && rootUrl.origin === origin) {
        productInfo = window.QlikMain?.PRODUCT_INFO;
      }
    } catch {}
  }
  if (!productInfo) {
    const { data, status } = await getProductInfo(options);
    productInfo = data;

    // Raw engine mode
    if (status === 404) {
      return result({ isUnknown: true });
    }

    if (!productInfo || (status <= 399 && status >= 300)) {
      // Assume we are on qlik-sense-server:
      // 3xx code means we get redirected to the login page and
      // in those cases we don't have the data.
      return result({ isQSE: true, isWindows: true });
    }
  }

  const deploymentType = (productInfo.composition?.deploymentType || "").toLowerCase();

  if (deploymentType === "qliksenseserver") {
    return result({ isQSE: true, isWindows: true, meta: extractMeta(productInfo) });
  }

  if (deploymentType === "qliksensedesktop") {
    return result({ isQSD: true, isWindows: true, meta: extractMeta(productInfo) });
  }

  if (deploymentType === "qliksensemobile") {
    return result({ isQSM: true, isQSE: true, isWindows: true, meta: extractMeta(productInfo) });
  }

  if (deploymentType === "qlikanalyticsmobileoffline") {
    return result({ isQSM: true, isQSMOffline: true, meta: extractMeta(productInfo) });
  }

  if (deploymentType === "cloud-console") {
    return result({ isCloud: true, isCloudConsole: true, meta: extractMeta(productInfo) });
  }

  if (productInfo.composition?.provider === "fedramp") {
    return result({ isCloud: true, isQCG: true, meta: extractMeta(productInfo) });
  }

  // If nothing is matched, we're on QCS
  return result({ isCloud: true, isQCS: true, meta: extractMeta(productInfo) });
};

