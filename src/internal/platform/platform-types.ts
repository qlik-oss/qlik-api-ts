/* -------------------------------------------------------------------------- */
/*                            platform module types                           */
/* -------------------------------------------------------------------------- */

/** Platform info from the environment the host config is configured to connect to */
export type Platform = {
  /**
   * Any cloud composition, such as QCS, QCG, qcs-int, Cloud-Console, etc.
   */
  isCloud: boolean;
  /**
   * Whether we're in a __QCS__ environment.
   */
  isQCS: boolean;
  /**
   * Whether we're in a __QCG__ environment.
   */
  isQCG: boolean;
  /**
   * If we're in a Cloud-Console environment, which is outside of QCS.
   */
  isCloudConsole: boolean;
  /**
   * Either Sense Server or Sense Desktop
   */
  isWindows: boolean;
  /**
   * Sense Server, also known as Sense Enterprise or QSEfW
   */
  isQSE: boolean;
  /**
   * Sense Desktop
   */
  isQSD: boolean;
  /**
   * Sense Mobile
   */
  isQSM: boolean;
  /**
   * Sense Mobile Offline
   */
  isQSMOffline: boolean;
  /**
   * Information to determine the composition is not present.
   */
  isUnknown: boolean;
  /**
   * Meta information from the product info.
   */
  meta?: ProductMeta;
};

/** Includes a subset of data from product-info */
export type ProductMeta = {
  /**
   * Unique product identifier.
   */
  productId: string;
  /**
   * Name of the product and a release label if its present. If nothing is resolved it's just 'Qlik'.
   */
  productLabel: string;
  /**
   * Product version, present for on-premise installations.
   */
  version?: string;
  /**
   * URL to the configured help website. All URLs include a trailing slash.
   */
  urls: {
    serverHelpBaseUrl: string;
    personalHelpBaseUrl: string;
    personalUpgradeBase: string;
    personalUpgradeUrl: string;
    qlikWebPageUrl: string;
  };
};

/** Data is accessible on `/resources/autogenerated/product-info.json` on any deployment */
export type ProductInfo = {
  composition?: {
    contentHash?: string;
    senseId: string;
    releaseLabel?: string; // `-` on QCS
    originalClassName?: string;
    productName?: string;
    version?: string;
    copyrightYearRange?: string;
    deploymentEnvironment?: string; // Used on QCS
    deploymentType?:
      | "qliksenseserver"
      | "qliksensedesktop"
      | "QlikSenseMobile"
      | "qlikanalyticsmobileoffline"
      | "qlikcloudservices"
      | "cloud-console";
    provider?: string; // Normally just "qlik", "fedramp" in QCG
  };
  externalUrls: {
    contentHash?: string;
    originalClassName?: string;
    personalUpgradeBase: string;
    cloudUploadUrl: string;
    serverHelpBaseUrl: string;
    personalHelpBaseUrl: string;
    personalUpgradeUrl: string;
    qlikWebPageUrl: string;
    cloudBaseUrl: string;
  };
};

export default {};
